import { test } from 'node:test'
import assert from 'node:assert/strict'
import { cleanUserText } from '../server/sources/user-text.ts'

test('a slash command shows what the user typed', () => {
  const raw = '<command-name>/goal</command-name>\n            <command-message>goal</command-message>\n            <command-args>deploy with all metrics ok</command-args>'
  assert.deepEqual(cleanUserText(raw), { kind: 'command', text: '/goal deploy with all metrics ok' })
})
test('a command without arguments, or without the leading slash', () => {
  assert.deepEqual(cleanUserText('<command-name>/context</command-name><command-message>context</command-message><command-args></command-args>'), { kind: 'command', text: '/context' })
  assert.equal(cleanUserText('<command-name>compact</command-name>').text, '/compact')
})
test('the local-command caveat is boilerplate and is skipped', () => {
  assert.equal(cleanUserText('<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>').kind, 'skip')
})
test('command output is kept as output, without colour codes; empty output is skipped', () => {
  assert.deepEqual(cleanUserText('<local-command-stdout>\u001b[1mGoal set\u001b[22m</local-command-stdout>'), { kind: 'output', text: 'Goal set' })
  assert.equal(cleanUserText('<local-command-stdout></local-command-stdout>').kind, 'skip')
})
test('ordinary text, even with angle brackets, is untouched', () => {
  assert.deepEqual(cleanUserText('use <b>bold</b> here'), { kind: 'text', text: 'use <b>bold</b> here' })
})

test('a shell escape shows as "! command" and its output as output (stdout and stderr together)', () => {
  assert.deepEqual(cleanUserText('<bash-input>open -e settings.json</bash-input>'), { kind: 'command', text: '! open -e settings.json' })
  assert.deepEqual(cleanUserText('<bash-stdout>ok</bash-stdout><bash-stderr>warn</bash-stderr>'), { kind: 'output', text: 'ok\nwarn' })
  assert.equal(cleanUserText('<bash-stdout></bash-stdout><bash-stderr></bash-stderr>').kind, 'skip')
})
test('a background task notification becomes one readable line', () => {
  const raw = '<task-notification>\n<task-id>b28</task-id>\n<status>completed</status>\n<summary>Background command "npm test" completed (exit code 0)</summary>\n</task-notification>'
  assert.deepEqual(cleanUserText(raw), { kind: 'output', text: 'Background task completed: Background command "npm test" completed (exit code 0)' })
  assert.equal(cleanUserText('<task-notification></task-notification>').text, 'Background task')
})
test('system reminders are dropped, also when mixed with real text', () => {
  assert.equal(cleanUserText('<system-reminder>context for the model</system-reminder>').kind, 'skip')
  assert.deepEqual(cleanUserText('<system-reminder>x</system-reminder>\nreal question'), { kind: 'text', text: 'real question' })
})
test('pasted content is unwrapped, keeping the surrounding text', () => {
  assert.deepEqual(cleanUserText('look at this:\n<pasted_content id="d245">\nline 1\nline 2\n</pasted_content>'), { kind: 'text', text: 'look at this:\nline 1\nline 2' })
})
test('the command-message tag may come before the command-name tag', () => {
  assert.equal(cleanUserText('<command-message>bridge</command-message>\n<command-name>/bridge</command-name>\n<command-args>review</command-args>').text, '/bridge review')
})
test('pasted content whose closing tag carries the id, or has none, is still unwrapped', () => {
  assert.equal(cleanUserText('\n\n<pasted_content id="d245">\nabc\n</pasted_content id="d245">\n').text, 'abc')
  assert.equal(cleanUserText('<pasted_content id="92c0">\ntruncated paste').text, 'truncated paste')
})
